def module_item(code, module, submenu, meaning_en, meaning_id, msg_en, msg_id,
                trigger_en, trigger_id, retry, action_en, action_id,
                audit="required", metric=None, alert=None):
    row = item(code, meaning_en, meaning_id, msg_en, msg_id, trigger_en, trigger_id,
               retry=retry, ui="module_specific", audit=audit, metric=metric, alert=alert)
    row["module"] = module
    row["submenu"] = submenu
    row["action_en"] = action_en
    row["action_id"] = action_id
    return row

